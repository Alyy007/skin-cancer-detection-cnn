import numpy as np
import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout
from sklearn.metrics import classification_report, accuracy_score

# Set random seeds for reproducibility
np.random.seed(42)
tf.random.set_seed(42)

# Configurations
IMG_HEIGHT, IMG_WIDTH = 128, 128  # Resizing to 128x128 for efficient training in Colab
BATCH_SIZE = 32

# Data Augmentation & Normalization for Training
# We will split the train_dir into 80% Training and 20% Validation
train_datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=20,
    width_shift_range=0.1,
    height_shift_range=0.1,
    horizontal_flip=True,
    validation_split=0.2  # 20% validation split
)

test_datagen = ImageDataGenerator(rescale=1./255)

# Generators
train_generator = train_datagen.flow_from_directory(
    train_dir,
    target_size=(IMG_HEIGHT, IMG_WIDTH),
    batch_size=BATCH_SIZE,
    class_mode='binary',
    subset='training',
    seed=42
)

val_generator = train_datagen.flow_from_directory(
    train_dir,
    target_size=(IMG_HEIGHT, IMG_WIDTH),
    batch_size=BATCH_SIZE,
    class_mode='binary',
    subset='validation',
    seed=42
)

test_generator = test_datagen.flow_from_directory(
    test_dir,
    target_size=(IMG_HEIGHT, IMG_WIDTH),
    batch_size=BATCH_SIZE,
    class_mode='binary',
    shuffle=False
)

# CNN Architecture
model = Sequential([
    Conv2D(32, (3, 3), activation='relu', input_shape=(IMG_HEIGHT, IMG_WIDTH, 3)),
    MaxPooling2D((2, 2)),

    Conv2D(64, (3, 3), activation='relu'),
    MaxPooling2D((2, 2)),

    Conv2D(128, (3, 3), activation='relu'),
    MaxPooling2D((2, 2)),

    Flatten(),
    Dense(128, activation='relu'),
    Dropout(0.5),
    Dense(1, activation='sigmoid')
])

model.compile(
    optimizer='adam',
    loss='binary_cross_entropy' if hasattr(tf.keras.losses, 'binary_cross_entropy') else 'binary_crossentropy',
    metrics=['accuracy']
)

model.summary()

# Train the model
history = model.fit(
    train_generator,
    validation_data=val_generator,
    epochs=10,
    verbose=1
)

# Predict on the test set
y_pred_prob = model.predict(test_generator)
y_pred = (y_pred_prob > 0.5).astype(int).flatten()
y_true = test_generator.classes

# Output metrics
acc = accuracy_score(y_true, y_pred)
print(f"\nTest Accuracy: {acc:.4f}")
print("\nClassification Report:")
print(classification_report(y_true, y_pred, target_names=test_generator.class_indices.keys()))

import pandas as pd

# Map indices back to class names
class_labels = {v: k for k, v in test_generator.class_indices.items()}

# Create a DataFrame with filenames, actual labels, and predicted labels
results_df = pd.DataFrame({
    'File_Path': test_generator.filenames,
    'Actual_Label': [class_labels[y] for y in y_true],
    'Predicted_Label': [class_labels[p] for p in y_pred],
    'Correct_Prediction': y_true == y_pred
})

# Display the first 20 rows of predictions
display(results_df.head(20))

# Print brief summary statistics
print("\n=== Prediction Summary ===")
print(results_df['Correct_Prediction'].value_counts(normalize=True))

# Save the trained CNN model
model_save_path = '/content/skin_cancer_cnn_model.keras'
model.save(model_save_path)
print(f"Model successfully saved to {model_save_path}")